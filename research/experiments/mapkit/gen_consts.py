#!/usr/bin/env python3 -I
"""Generate consts.m (our own code): a tiny simulator command-line tool that
prints the runtime string value of every exported MapKit string constant
named in the level-4 name inventory, plus MKErrorDomain.
Usage: python3 -I gen_consts.py <objc-names.json> > consts.m"""
import json, sys
d = json.load(open(sys.argv[1]))
names = [c['name'] for c in d['constants']] + ['MKErrorDomain']
print('// Generated by gen_consts.py. Prints "name=value" for MapKit string constants.')
print('#import <MapKit/MapKit.h>')
print('int main(void) { @autoreleasepool {')
for n in names:
    print(f'  printf("%s=%s\\n", "{n}", [(NSString *){n} UTF8String]);')
print('} return 0; }')
