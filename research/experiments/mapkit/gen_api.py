#!/usr/bin/env python3 -I
"""Render specs/frameworks/mapkit/api-inventory.md from the name inventories
produced by extract_objc_names.py and extract_swift_names.py (level 4: names,
superclasses, enum raw values, iOS introduction versions only).

Usage: python3 -I gen_api.py <objc-names.json> <swiftui-names.json> <overlay-names.json> > api-inventory.md
"""
import json, re, sys
from collections import OrderedDict

objc = json.load(open(sys.argv[1]))
swiftui = json.load(open(sys.argv[2]))
overlay = json.load(open(sys.argv[3]))

def ver(v, dep=None):
    s = ''
    if v and v != 'unavailable':
        s = f' [{v}]'
    elif v == 'unavailable':
        s = ' (unavailable)'
    if dep:
        s += ' (deprecated)'
    return s

out = []
w = out.append
w('<!-- Generated by research/experiments/mapkit/gen_api.py; edit the generator, not this file. -->')
w('# MapKit spec: API name inventory')
w('')
w('Part of `specs/frameworks/mapkit/`. Names from the public iOS 27.1 simulator SDK')
w('(level 4): Objective-C classes with superclass, iOS introduction version and')
w('member names; protocols; enumerations with raw values; exported constants and')
w('functions; then the SwiftUI MapKit module and the Swift overlay. A member marked')
w('`+` is a class member, `(ro)` read-only; a version in brackets is the member\'s')
w('own introduction version when it differs from its type; `(deprecated)` and')
w('`(unavailable)` refer to iOS. No declarations, types or documentation are')
w('reproduced. Behavior is specified in `interface.md`.')
w('')

# ---- Objective-C classes (merge categories by name)
classes = OrderedDict()
for c in sorted(objc['classes'], key=lambda c: c['name']):
    e = classes.setdefault(c['name'], {'super': None, 'ios': None, 'dep': None, 'members': [], 'cats': []})
    if c['super']:
        e['super'] = c['super']
    if c['category'] is None or e['ios'] is None:
        e['ios'] = e['ios'] or c['ios']
        e['dep'] = e['dep'] or c['deprecated']
    if c['category']:
        e['cats'].append(c['category'])
    e['members'].extend(c['members'])
w('## 1. Objective-C classes')
w('')
for name, e in classes.items():
    if not name.startswith('MK'):
        head = f'### `{name}` (MapKit category)'
    else:
        head = f'### `{name}`' + (f' : `{e["super"]}`' if e['super'] else '') + (f' (iOS {e["ios"]})' if e['ios'] and e['ios'] != 'unavailable' else '') + (' (deprecated)' if e['dep'] else '') + (' (unavailable on iOS)' if e['ios'] == 'unavailable' else '')
    w(head)
    w('')
    seen, items = set(), []
    for m in e['members']:
        key = (m['k'], m['name'])
        if key in seen:
            continue
        seen.add(key)
        n = ('+' if m['k'] in ('class-method', 'class-prop') else '') + f'`{m["name"]}`'
        if m.get('readonly'):
            n += ' (ro)'
        mv = m['ios'] if m['ios'] != e['ios'] else None
        n += ver(mv, m['deprecated'])
        items.append(n)
    w('- ' + (', '.join(items) if items else '(no members)'))
    w('')

w('## 2. Protocols')
w('')
for p in sorted(objc['protocols'], key=lambda p: p['name']):
    items = []
    for m in p['members']:
        n = ('+' if m['k'] in ('class-method', 'class-prop') else '') + f'`{m["name"]}`' + (' (ro)' if m.get('readonly') else '') + ver(m['ios'] if m['ios'] != p['ios'] else None, m['deprecated'])
        items.append(n)
    w(f'### `{p["name"]}`' + (f' (iOS {p["ios"]})' if p['ios'] and p['ios'] != 'unavailable' else ''))
    w('')
    w('- ' + (', '.join(items) if items else '(no members)'))
    w('')

known = {c['name']: c['value'] for e in objc['enums'] for c in e['cases'] if isinstance(c['value'], int)}
for e in objc['enums']:
    for c in e['cases']:
        if isinstance(c['value'], str):
            try:
                c['value'] = eval(re.sub(r'\b([A-Za-z_]\w*)\b', lambda x: str(known.get(x.group(1), x.group(1))), c['value']), {'__builtins__': {}}, {})
            except Exception:
                pass
w('## 3. Enumerations and option sets (raw values)')
w('')
for e in sorted(objc['enums'], key=lambda e: e['name']):
    w(f'### `{e["name"]}`' + (f' (iOS {e["ios"]})' if e['ios'] and e['ios'] != 'unavailable' else '') + (' (deprecated)' if e['deprecated'] else ''))
    w('')
    w('| Case | Value | Note |')
    w('|---|---|---|')
    for c in e['cases']:
        val = c['value']
        if isinstance(val, int) and val > 255 and e['name'] in ('MKDirectionsTransportType',):
            val = hex(val)
        note = ver(c['ios'] if c['ios'] != e['ios'] else None, c['deprecated']).strip()
        w(f'| `{c["name"]}` | {val} | {note} |')
    w('')

w('## 4. Exported constants and functions')
w('')
w('String values of the string constants are in `interface.md` §11 (measured).')
w('')
w('| Name | Kind | iOS |')
w('|---|---|---|')
for c in sorted(objc['constants'], key=lambda c: c['name']):
    w(f'| `{c["name"]}` | {c["kind"]} | {(c["ios"] or "")}{" (deprecated)" if c["deprecated"] else ""} |')
for f in sorted({f['name']: f for f in objc['functions']}.values(), key=lambda f: f['name']):
    w(f'| `{f["name"]}` | function | {(f["ios"] or "")}{" (deprecated)" if f["deprecated"] else ""} |')
w('')

def clean(n):
    n = re.sub(r'@\w+(<[^>]*>)?', '', n)
    if n in ('(lhs:rhs:)', '(a:b:)'):
        return '=='
    return n

def swift_section(title, items):
    w(title)
    w('')
    types = OrderedDict()
    for e in items:
        if e['kind'] == 'extension' and not e['members']:
            continue
        key = (e['name'])
        t = types.setdefault(key, {'kind': e['kind'], 'ios': e['ios'], 'unavailable': e['unavailable'], 'members': [], 'ext': e['kind'] == 'extension'})
        if e['kind'] != 'extension':
            t['kind'] = e['kind']; t['ios'] = e['ios']; t['unavailable'] = e['unavailable']; t['ext'] = False
        t['members'].extend(e['members'])
    for name, t in types.items():
        if name.startswith('_'):
            continue
        label = 'extension' if t['ext'] else t['kind']
        head = f'### {label} `{name}`'
        if t['unavailable']:
            head += ' (unavailable on iOS)'
        elif t['ios']:
            head += f' (iOS {t["ios"]})'
        w(head)
        w('')
        seen, ms = set(), []
        for m in t['members']:
            n = clean(m['name'])
            if n.startswith('_') or (m['k'], n) in seen:
                continue
            seen.add((m['k'], n))
            s = ('static ' if m.get('static') else '') + f'`{n}`'
            if m['unavailable']:
                s += ' (unavailable)'
            elif m['ios'] and m['ios'] != t['ios']:
                s += f' [{m["ios"]}]'
            ms.append(s)
        w('- ' + (', '.join(ms) if ms else '(no public members besides conformances)'))
        w('')

swift_section('## 5. SwiftUI (`_MapKit_SwiftUI`, imported through `import MapKit` + `import SwiftUI`)', swiftui)
swift_section('## 6. Swift overlay refinements (`MapKit` module)', overlay)
sys.stdout.write('\n'.join(out).rstrip() + '\n')
