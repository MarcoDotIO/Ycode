#!/bin/sh
# Generate the interposer's export trampolines from a library's exported
# symbol NAMES (nm -gU, level-4 metadata). Original Ycode code.
# Usage: gen_tramps.sh <real dylib> <out dir> [allowlist]
# With an allowlist (one function name per line, no leading underscore) only
# those functions are exported, to test which names a client needs.
# Writes <out>/tramps.s (one forwarding stub per exported function) and
# <out>/tramps_table.c (the name table and copies of exported data pointers).
set -e
LIB=${1:?real dylib}
OUT=${2:?out dir}
mkdir -p "$OUT"
nm -gU "$LIB" > "$OUT/exports.all.txt"
if [ -n "$3" ]; then
  awk 'NR==FNR{keep["_"$1]=1; next} $2!="T" || keep[$3]' "$3" "$OUT/exports.all.txt" > "$OUT/exports.txt"
else
  cp "$OUT/exports.all.txt" "$OUT/exports.txt"
fi

{
  echo "// generated by gen_tramps.sh from exported symbol names"
  echo ".text"
  i=0
  awk '$2=="T"{print $3}' "$OUT/exports.txt" | while read -r sym; do
    echo ".globl $sym"
    echo ".p2align 2"
    echo "$sym:"
    echo "    mov x16, #$i"
    echo "    b _sfbt_common"
    i=$((i+1))
  done
} > "$OUT/tramps.s"

{
  echo "// generated by gen_tramps.sh from exported symbol names"
  echo "#include <stddef.h>"
  echo "const char *const sfbt_names[] = {"
  awk '$2=="T"{sub(/^_/,"",$3); print "  \"" $3 "\","}' "$OUT/exports.txt"
  echo "};"
  echo "const size_t sfbt_count = sizeof sfbt_names / sizeof sfbt_names[0];"
  # Exported data that is not ObjC metadata: re-exported as pointer-sized
  # copies filled from the real library at load time.
  echo "const char *const sfbt_data_names[] = {"
  awk '$2=="S" && $3 !~ /OBJC_/ {sub(/^_/,"",$3); print "  \"" $3 "\","}' "$OUT/exports.txt"
  echo "};"
  echo "const size_t sfbt_data_count = sizeof sfbt_data_names / sizeof sfbt_data_names[0];"
  awk '$2=="S" && $3 !~ /OBJC_/ {sub(/^_/,"",$3); print "__attribute__((visibility(\"default\"))) void *" $3 "[512];"}' "$OUT/exports.txt"
  echo "void *const sfbt_data_vars[] = {"
  awk '$2=="S" && $3 !~ /OBJC_/ {sub(/^_/,"",$3); print "  (void *)" $3 ","}' "$OUT/exports.txt"
  echo "};"
} > "$OUT/tramps_table.c"
echo "generated $(grep -c b\ _sfbt_common "$OUT/tramps.s") trampolines"
