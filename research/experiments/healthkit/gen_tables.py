#!/usr/bin/env python3 -I
"""Generate the identifier and enumeration appendices of the HealthKit spec.

Our own tool. Inputs:
  1. the name inventory made by extract_names.py (level 4: names, enum raw
     values, introduced iOS versions);
  2. the "basic" phase report of our HealthProbe app (level 3: the runtime
     string value of every constant, the object-type class, aggregation style,
     compatible units and duration limits).
Output: Markdown tables (names, values and numbers only) on stdout.

Usage: python3 -I gen_tables.py inventory.json basic.txt > identifiers.md
"""
import json, re, sys

inv = json.load(open(sys.argv[1]))
obs = {}
for line in open(sys.argv[2], encoding='utf-8'):
    m = re.search(r' id (\S+) kind=(\S+) value=(\S+)(.*)$', line)
    if not m:
        continue
    rest = m.group(4)
    d = {'value': m.group(3)}
    for k in ('class', 'maxDur', 'minDur', 'agg', 'units', 'perObject', 'recal'):
        km = re.search(r'\b' + k + r'=(\S+)', rest)
        if km:
            d[k] = km.group(1)
    obs[m.group(1)] = d

AGG = {'0': 'cumulative', '1': 'discrete (arithmetic)', '2': 'discrete (temporally weighted)', '3': 'discrete (equivalent continuous level)'}
DIM = [('count', 'scalar (count)'), ('g', 'mass'), ('m', 'length'), ('s', 'time'), ('J', 'energy'), ('K', 'temperature'),
       ('Pa', 'pressure'), ('L', 'volume'), ('S', 'conductance'), ('V', 'electric potential'), ('W', 'power'),
       ('dBASPL', 'sound pressure level'), ('dBHL', 'hearing level'), ('IU', 'pharmacology (IU)'), ('Hz', 'frequency'),
       ('lx', 'illuminance'), ('rad', 'angle'), ('D', 'optical power'), ('appleEffortScore', 'effort score'),
       ('m/s', 'speed'), ('g/L', 'mass concentration'), ('L/s', 'volume flow'), ('m^2', 'area'),
       ('mL/min·kg', 'VO2 rate'), ('kcal/hr·kg', 'energy rate per mass'), ('s/m', 'pace'), ('count/m', 'per length'),
       ('m/s^2', 'acceleration'), ('W/kg', 'power per mass'), ('J/kg', 'energy per mass')]

def dim(units):
    us = units.split('|') if units else []
    if 'Hz' in us or 'count/s' in us:
        return 'frequency (count/time)'
    for u, name in DIM:
        if u in us:
            return name
    return '?'

def ver(c):
    v = c.get('ios')
    s = v if v else '—'
    if c.get('deprecated'):
        s += ' (deprecated ' + (c['deprecated'] if c['deprecated'] != 'yes' else '') + ')'
    return s.replace(' )', ')')

out = []
P = out.append
P('<!-- Generated by research/experiments/healthkit/gen_tables.py; edit the generator, not this file. -->')
P('# HealthKit spec: identifier and enumeration appendix\n')
P('Part of `specs/frameworks/healthkit/`. Every table row is an interop fact: a public')
P('symbol name, the string value or raw number it has at run time, and the iOS version')
P('that introduced it. Columns marked (L3) were measured by `HealthProbe` on the iOS')
P('27.1 and 27.0 simulator runtimes (identical results); "iOS" is the introduction')
P('version from SDK availability metadata (L4). No declarations or documentation text')
P('are reproduced.\n')
P('Conventions: "agg" is the quantity type\'s aggregation style (L3, raw value in')
P('brackets); "dimension" is the unit family the type accepts, found by testing')
P('compatibility against a fixed list of base units (L3); "max" is the maximum')
P('allowed sample duration in seconds when the type restricts it (L3; 345600 s = 4')
P('days); "per-object" means the type uses per-object read authorization (L3).\n')

kinds = [('HKQuantityTypeIdentifier', 'Quantity types'), ('HKCategoryTypeIdentifier', 'Category types'),
         ('HKCharacteristicTypeIdentifier', 'Characteristic types'), ('HKCorrelationTypeIdentifier', 'Correlation types'),
         ('HKDocumentTypeIdentifier', 'Document types'), ('HKClinicalTypeIdentifier', 'Clinical record types'),
         ('HKScoredAssessmentTypeIdentifier', 'Scored assessment types')]
for kind, title in kinds:
    rows = [c for c in inv['constants'] if c['kind'] == kind]
    P(f'## {title} ({len(rows)})\n')
    if kind == 'HKQuantityTypeIdentifier':
        P('| Identifier (= string value) | iOS | agg | dimension | max | min |')
        P('|---|---|---|---|---|---|')
    else:
        P('| Identifier | String value | iOS | Class (L3) | max | per-object |')
        P('|---|---|---|---|---|---|')
    for c in sorted(rows, key=lambda c: c['name']):
        o = obs.get(c['name'], {})
        mx = o.get('maxDur', '')
        mx = mx.split(':')[1] if mx.startswith('1:') else ('none' if mx == '0' else 'n/a')
        mn = o.get('minDur', '')
        mn = mn.split(':')[1] if mn.startswith('1:') else ('none' if mn == '0' else 'n/a')
        if kind == 'HKQuantityTypeIdentifier':
            same = '' if o.get('value') == c['name'] else f' (value `{o.get("value")}`)'
            P(f'| `{c["name"]}`{same} | {ver(c)} | {AGG.get(o.get("agg"), "?")} [{o.get("agg", "?")}] | {dim(o.get("units", ""))} | {mx} | {mn} |')
        else:
            P(f'| `{c["name"]}` | `{o.get("value", "?")}` | {ver(c)} | {o.get("class", "?")} | {mx} | {"yes" if o.get("perObject") == "1" else "no"} |')
    P('')

P('## Other string constants\n')
P('Metadata keys, predicate key paths, device property keys, sort identifiers,')
P('notification names, error domain, workout-route and series identifiers, and the')
P('string-valued enumerations (FHIR, verifiable records, medication forms). Note that')
P('many metadata keys have a string value that differs from the symbol name.\n')
P('| Symbol | String value (L3) | iOS | Header group |')
P('|---|---|---|---|')
other = [c for c in inv['constants'] if c['kind'] not in dict(kinds) and c['kind'] != 'NSOperatingSystemVersion']
for c in sorted(other, key=lambda c: (c['file'], c['name'])):
    o = obs.get(c['name'], {})
    P(f'| `{c["name"]}` | `{o.get("value", "?")}` | {ver(c)} | {c["file"].replace(".h", "")} |')
P('')

P('## Enumerations\n')
P('Raw values (L4, from SDK enum metadata). Cases are listed in declaration order.\n')
for e in inv['enums']:
    P(f'### `{e["name"]}` (iOS {e["ios"] or "—"})\n')
    parts = []
    for c in e['cases']:
        v = c['value']
        s = f'`{c["name"]}` = {v}'
        if c.get('ios') and e.get('ios') and c['ios'] != e['ios']:
            s += f' (iOS {c["ios"]})'
        if c.get('deprecated'):
            s += ' (deprecated)'
        parts.append(s)
    P('; '.join(parts) + '\n')

P('## Functions\n')
P('| Function | iOS |')
P('|---|---|')
for f in inv['functions']:
    P(f'| `{f["name"]}` | {"marked unavailable on iOS" if f["ios"] == "unavailable" else (f["ios"] or "see header group")} |')
P('')
print('\n'.join(out))
