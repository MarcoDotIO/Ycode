#!/usr/bin/env python3 -I
"""Generate the class/member NAME inventory of the HealthKit spec (level 4).

Our own tool. Input: the inventory from extract_names.py. Output: Markdown
listing, per class (and category), its superclass, introduction version and
the names of its members (selectors and property names only; no types, no
parameter lists, no documentation).

Usage: python3 -I gen_api.py inventory.json > api-inventory.md
"""
import json, sys
inv = json.load(open(sys.argv[1]))
out = ['<!-- Generated by research/experiments/healthkit/gen_api.py; edit the generator, not this file. -->',
       '# HealthKit spec: API name inventory', '',
       'Part of `specs/frameworks/healthkit/`. The Objective-C classes of the iOS 27.1 SDK',
       'with their superclass, iOS introduction version and member names (level 4). A',
       'member marked `+` is a class member; `(ro)` is a read-only property; a version in',
       'brackets is the member\'s own introduction version when it differs from the class;',
       '`unavailable` means the member is marked unavailable on iOS. Swift refinements',
       '(async variants, Swift-only query descriptors) are in `interface.md` §9.', '']
by = {}
for c in inv['classes']:
    by.setdefault(c['name'], []).append(c)
for name in sorted(by):
    entries = by[name]
    base = next((e for e in entries if not e['category']), entries[0])
    out.append(f"## `{name}`" + (f" : `{base['super']}`" if base.get('super') else '') + f" (iOS {base['ios'] or '—'})")
    out.append('')
    for e in entries:
        mem = []
        for m in e['members']:
            if m['name'] in ('init', 'new') and m['k'] in ('method', 'class-method'):
                pref = '+' if m['k'] == 'class-method' else ''
                mem.append(f'{pref}`{m["name"]}`'); continue
            s = ('+' if m['k'] in ('class-method', 'class-prop') else '') + f'`{m["name"]}`'
            if m.get('readonly'):
                s += ' (ro)'
            if m.get('ios') and m['ios'] != e.get('ios'):
                s += f' [{m["ios"]}]'
            if m.get('deprecated'):
                s += ' (deprecated)'
            mem.append(s)
        seen = []
        for x in mem:
            if x not in seen:
                seen.append(x)
        label = f"Category `{e['category']}`: " if e['category'] else ''
        out.append('- ' + label + (', '.join(seen) if seen else '(no members)'))
    out.append('')
out.append('## Protocols\n')
for p in inv['protocols']:
    out.append(f"- `{p['name']}` (iOS {p['ios'] or '—'}): " + ', '.join(f'`{m["name"]}`' for m in p['members']))
print('\n'.join(out))
