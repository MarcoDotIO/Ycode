"""Builds the golden layout tables from a SUIProbe layout-mode log and the
probe's own case sources (KIT-SWIFTUI, original code).
Usage: python3 -I mkgolden.py Layout.swift layout.log > golden-layout.md"""
import re, sys, collections

src, logp = sys.argv[1], sys.argv[2]
code = {}
for l in open(src):
    m = re.match(r'\s*add\("([^"]+)"(?:, place: ProposedViewSize\(width: (\d+), height: (\d+)\))?(?:, proposals: [^)]*\]?\)?)?\)?\s*\{\s*(.*)\}\s*$', l)
    if m:
        code[m.group(1)] = (m.group(4).strip(), m.group(2), m.group(3))
whole = open(src).read()
for m in re.finditer(r'add\("([^"]+)"[^{]*\{', whole):
    if m.group(1) in code:
        continue
    i = m.end(); depth = 1; j = i
    while j < len(whole) and depth:
        depth += {'{': 1, '}': -1}.get(whole[j], 0); j += 1
    body = re.sub(r'\s+', ' ', whole[i:j - 1]).strip()
    pm = re.search(r'place: ProposedViewSize\(width: (\d+), height: (\d+)\)', whole[m.start():m.end()])
    code[m.group(1)] = (body, pm.group(1) if pm else None, pm.group(2) if pm else None)
vals = collections.OrderedDict()
for l in open(logp, errors='replace'):
    m = re.match(r'^SUP layout\.(.+?)\.(fit\[[^\]]+\]|dims\[[^\]]+\]|frame\.[\w]+|priority|spacing\.[\w>-]+)=(.*)$', l.strip())
    if m:
        vals.setdefault(m.group(1), collections.OrderedDict())[m.group(2)] = m.group(3)
P = ['nilxnil', '0.00x0.00', 'infxinf', '100.00xnil', 'nilx100.00', '100.00x100.00', '300.00x500.00']
H = ['nil×nil', '0×0', '∞×∞', '100×nil', 'nil×100', '100×100', '300×500']
def short(v):
    return v.replace('.00', '').replace('inf', '∞')
print('# SwiftUI: golden layout values (iOS 27.1 simulator, iPhone Duo)')
print()
print('Status: generated, round 0 (KIT-SWIFTUI, 2026-10-19). Level 3: our probe app')
print('(`research/experiments/swiftui/SUIProbe/`, mode `layout`) on Apple\'s simulator; generated by')
print('`mkgolden.py` from the run log. Font: the system font of the iOS 27.1 runtime at the default')
print('content size (Large). Values are points; `.33`/`.67` are thirds of a point (pixel grid at scale 3).')
print()
print('How to read: **fit[p]** = size the view returns when proposed `p` (`nil` = unspecified dimension,')
print('`∞` = infinity). **placed** = proposal used to place the view in the test container')
print('(default 300×500). **frames** = frames of probed descendants in the container\'s coordinate')
print('space after placement (x, y, width, height). **dims** = alignment guides of the placed view.')
print()
print('Text-dependent values (anything containing `Text`, `Label`, `Button`, symbols) depend on the')
print('font\'s metrics and are exact only with the same font; an open implementation with another font')
print('checks them as *relations* (see `10-plan.md` §3). Shape, colour, spacer, frame, padding, stack')
print('and grid arithmetic around fixed-size children are font-independent and must match exactly.')
print()
print('Rows for UIKit-backed containers (`list.*`, `form.*`, `navigationStack*`, `tabView`) are')
print('informative only: their content is hosted in separate UIKit views, and descendant frames in the')
print('container\'s coordinate space are not reliable (use the global frames in `06-app-and-components.md`).')
print()
print('| Case | View (our probe source) | placed | ' + ' | '.join(f'fit[{h}]' for h in H) + ' | frames / dims |')
print('|---|---|---|' + '---|' * len(H) + '---|')
for name, d in vals.items():
    if name == 'spacingMatrix' or not any(k.startswith('fit[') or k.startswith('dims') for k in d):
        continue
    c = code.get(name, ('?', None, None))
    if name.startswith('font.'):
        c = (f'Text("Ag").font(.{name[5:]})', None, None)
    elif name.startswith('dyn.'):
        c = (f'VStack(alignment: .leading, spacing: 0) {{ Text("Ag").font(style) for each text style }}.environment(\\.dynamicTypeSize, .{name[4:]})', None, None)
    place = f'{c[1]}×{c[2]}' if c[1] else '300×500'
    fits = [short(d.get(f'fit[{p}]', '–')) for p in P]
    frames = '; '.join(f'{k[6:]}={short(v)}' for k, v in d.items() if k.startswith('frame.'))
    dims = [v for k, v in d.items() if k.startswith('dims')]
    extra = ''
    if dims:
        dm = re.search(r'firstBaseline=(\S+) lastBaseline=(\S+)', dims[0])
        if dm and 'Text' in c[0] or 'font' in name or 'dyn' in name:
            extra = f'baselines {short(dm.group(1))}/{short(dm.group(2))}' if dm else ''
    pr = d.get('priority')
    if pr and pr != '0.00':
        extra += f' priority={short(pr)}'
    cell = '; '.join(x for x in [frames, extra.strip()] if x)
    view = c[0].replace('|', '\\|')
    if len(view) > 150:
        view = view[:147] + '…'
    print(f'| `{name}` | `{view}` | {place} | ' + ' | '.join(fits) + f' | {cell} |')
sp = vals.get('spacingMatrix')
if sp:
    labels = []
    for k in sp:
        if not k.startswith('spacing.') or '->' not in k:
            continue
        a, b = k[len('spacing.'):].split('->')
        if a not in labels:
            labels.append(a)
    print()
    print('## Default spacing between kinds of views')
    print()
    print('`ViewSpacing.distance(to:along:)` from the row view to the column view, horizontal / vertical.')
    print('Views: `text` = Text("A"), `textCaption` = caption font, `image` = SF Symbol, `color` = 10×10 colour,')
    print('`button` = Button, `toggle` = Toggle without label, `textField` = TextField, `padded` = Text with `.padding()`.')
    print()
    print('| from \\ to | ' + ' | '.join(labels) + ' |')
    print('|---|' + '---|' * len(labels))
    for a in labels:
        row = []
        for b in labels:
            v = sp.get(f'spacing.{a}->{b}', '')
            m = re.match(r'h=(\S+) v=(\S+)', v)
            row.append(f'{short(m.group(1))} / {short(m.group(2))}' if m else '–')
        print(f'| {a} | ' + ' | '.join(row) + ' |')
print()
print('## Evidence')
print()
print('| Claim | Level |')
print('|---|---|')
print('| Every value in this file | 3 (black-box run of our own app on the iOS 27.1 simulator) |')
