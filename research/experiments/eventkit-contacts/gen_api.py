#!/usr/bin/env python3 -I
"""Generate the NAME appendices of the EventKit and Contacts specs (level 4).

Our own tool. Input: the inventory written by extract_names.py and, for the
Contacts string constants, a CNProbe "basic" report (level 3: the values the
running framework returns). Output: two Markdown files per framework family:

  api-inventory.md   classes with superclass, iOS introduction version and
                     member names (selectors and property names only; no
                     types, no parameter lists, no documentation)
  identifiers.md     every enumeration with its case names and raw values,
                     and every exported string constant with its value

Usage: python3 -I gen_api.py inventory.json cn-basic.txt OUTDIR [ek-basic.txt]
  writes OUTDIR/eventkit/{api-inventory,identifiers}.md and
         OUTDIR/contacts/{api-inventory,identifiers}.md
"""
import json, os, re, sys

inv = json.load(open(sys.argv[1]))
values = {}
for line in open(sys.argv[2], encoding='utf-8'):
    m = re.search(r' const (\w+)="(.*)"$', line.rstrip('\n'))
    if m:
        values[m.group(1)] = m.group(2)
if len(sys.argv) > 4:  # EKProbe "basic" report: "NAME=value" pairs on one line
    for line in open(sys.argv[4], encoding='utf-8'):
        if ' EKErrorDomain=' in line:
            for k, v in re.findall(r'(EK\w+)=(\S+)', line):
                values[k] = v
outdir = sys.argv[3]

FAMILIES = {
    'eventkit': (('EventKit', 'EventKitUI'), 'EventKit and EventKitUI'),
    'contacts': (('Contacts', 'ContactsUI'), 'Contacts and ContactsUI'),
}
GEN = '<!-- Generated by research/experiments/eventkit-contacts/gen_api.py; edit the generator, not this file. -->'


def member_list(e):
    mem = []
    for m in e['members']:
        s = ('+' if m['k'] in ('class-method', 'class-prop') else '') + f'`{m["name"]}`'
        if m.get('readonly'):
            s += ' (ro)'
        if m.get('ios') and m['ios'] != e.get('ios'):
            s += f' [{m["ios"]}]'
        if m.get('deprecated'):
            s += ' (deprecated)'
        if s not in mem:
            mem.append(s)
    return mem


def api(key, fws, title):
    out = [GEN, f'# {title.split(" and ")[0]} spec: API name inventory', '',
           f'Part of `specs/frameworks/{key}/`. The Objective-C classes of {title} in the',
           'iOS 27.1 SDK with their superclass, iOS introduction version and member names',
           '(level 4). `+` marks a class member, `(ro)` a read-only property; a version in',
           'brackets is the member\'s own introduction version when it differs from the',
           'class; `(deprecated)` means the SDK marks it deprecated. Swift-only additions',
           'are listed in `interface.md`.', '']
    for fw in fws:
        out += [f'## {fw}', '']
        by = {}
        for c in inv['classes']:
            if c['fw'] == fw:
                by.setdefault(c['name'], []).append(c)
        for name in sorted(by):
            entries = by[name]
            base = next((e for e in entries if not e['category']), entries[0])
            sup = f" : `{base['super']}`" if base.get('super') else ''
            out.append(f"### `{name}`{sup} (iOS {base['ios'] or '—'})")
            out.append('')
            for e in entries:
                label = f"Category `{e['category']}`: " if e['category'] else ''
                mem = member_list(e)
                out.append('- ' + label + (', '.join(mem) if mem else '(no members)'))
            out.append('')
        prots = [p for p in inv['protocols'] if p['fw'] == fw]
        if prots:
            out += ['### Protocols', '']
            for p in prots:
                out.append(f"- `{p['name']}` (iOS {p['ios'] or '—'}): " + (', '.join(member_list(p)) or '(no members)'))
            out.append('')
    return '\n'.join(out) + '\n'


def ident(key, fws, title):
    out = [GEN, f'# {title.split(" and ")[0]} spec: enumerations and string constants', '',
           f'Part of `specs/frameworks/{key}/`. Every enumeration of {title} in the iOS 27.1',
           'SDK with its case names and raw values (level 4), and every exported string',
           'constant. Constant values were read from the running framework by our probe',
           '(level 3); they are interop identifiers (dictionary keys, labels, notification',
           'names) that apps compare against, so Ycode must return the same strings.', '']
    for fw in fws:
        enums = [e for e in inv['enums'] if e['fw'] == fw]
        if enums:
            out += [f'## {fw} enumerations', '']
            for e in sorted(enums, key=lambda x: x['name']):
                intro = f" (iOS {e['ios']})" if e.get('ios') else ''
                out += [f"### `{e['name']}`{intro}", '', '| Case | Value | Notes |', '|---|---|---|']
                for c in e['cases']:
                    notes = []
                    if c.get('ios') and c['ios'] != e.get('ios'):
                        notes.append(f"iOS {c['ios']}")
                    if c.get('deprecated'):
                        notes.append('deprecated')
                    out.append(f"| `{c['name']}` | {c['value']} | {', '.join(notes)} |")
                out.append('')
        consts = [c for c in inv['constants'] if c['fw'] == fw]
        if consts:
            out += [f'## {fw} string constants', '', '| Constant | Value | iOS |', '|---|---|---|']
            for c in sorted(consts, key=lambda x: x['name']):
                v = values.get(c['name'])
                vs = f'`{v}`' if v is not None else '(not read by the probe)'
                if v == '':
                    vs = '(empty string)'
                out.append(f"| `{c['name']}` | {vs} | {c['ios'] or ''}{' (deprecated)' if c.get('deprecated') else ''} |")
            out.append('')
    return '\n'.join(out) + '\n'


for key, (fws, title) in FAMILIES.items():
    d = os.path.join(outdir, key)
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'api-inventory.md'), 'w', encoding='utf-8').write(api(key, fws, title))
    open(os.path.join(d, 'identifiers.md'), 'w', encoding='utf-8').write(ident(key, fws, title))
