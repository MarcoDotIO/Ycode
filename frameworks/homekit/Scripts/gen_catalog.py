#!/usr/bin/env python3 -I
"""Generate the HomeKit type catalog from the clean-room spec.

Input:  specs/frameworks/homekit/type-identifiers.md
Output: Sources/HomeKit/Generated/{Constants,Catalog,ValueEnums}.swift

Run from anywhere:   python3 -I frameworks/homekit/Scripts/gen_catalog.py
Check (no writes):   python3 -I frameworks/homekit/Scripts/gen_catalog.py --check
The output is committed; re-run after the spec changes.

Naming: constant names are the spec's names with their table prefix
(`HMServiceType` + `Lightbulb`). Enumeration case names follow the public Swift
import rules for Objective-C enumerators: strip the enumeration's name, lower-case
the leading word (a run of capitals is one word, so `HDMI` -> `hdmi`,
`SVideo` -> `sVideo`); when the rest starts with a digit, the enumeration's last
word is kept (`AirParticulateSize` + `2_5` -> `size2_5`).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(PKG))
SPEC = os.path.join(REPO, "specs", "frameworks", "homekit", "type-identifiers.md")
OUT = os.path.join(PKG, "Sources", "HomeKit", "Generated")

HAP_BASE_SUFFIX = "-0000-1000-8000-0026BB765291"
HEADER = ("// Generated by Scripts/gen_catalog.py from specs/frameworks/homekit/type-identifiers.md.\n"
          "// Do not edit; re-run the script instead.\n")
KEYWORDS = {"default", "in", "is", "as", "case", "open", "self", "init", "true", "false",
            "nil", "repeat", "return", "switch", "protocol", "internal", "public", "private"}


def sections(text):
    """Map '#### Title (n)' headings to their table rows (lists of cells)."""
    out = {}
    current = None
    for line in text.splitlines():
        m = re.match(r"^#### (.+?) \((\d+)\)\s*$", line)
        if m:
            current = (m.group(1), int(m.group(2)))
            out[current] = []
            continue
        if line.startswith("## "):
            current = None
            continue
        if current and line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if set("".join(cells)) <= set("-: "):
                continue
            out[current].append(cells)
    result = {}
    for (title, count), rows in out.items():
        rows = rows[1:]  # header row
        if len(rows) != count:
            sys.exit(f"{title}: expected {count} rows, found {len(rows)}")
        result[title] = rows
    return result


def enum_table(text):
    m = re.search(r"^## 5\. Characteristic value enumerations$(.*?)^## Evidence", text, re.S | re.M)
    if not m:
        sys.exit("value enumeration section not found")
    rows = []
    for line in m.group(1).splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells[0] in ("Enumeration",) or set("".join(cells)) <= set("-: "):
            continue
        name, ios, values = cells
        cases = []
        for item in values.split(","):
            num, label = item.strip().split(" ", 1)
            cases.append((int(num), label.strip()))
        rows.append((name, ios, cases))
    return rows


def lower_leading_word(s):
    n = 0
    while n < len(s) and s[n].isupper():
        n += 1
    if n == 0:
        return s
    if n == len(s):
        return s.lower()
    if n == 1:
        return s[0].lower() + s[1:]
    if s[n].islower():
        return s[:n - 1].lower() + s[n - 1:]
    return s[:n].lower() + s[n:]


def last_word(name):
    words = re.findall(r"[A-Z][a-z0-9]*|[0-9]+", name)
    return words[-1] if words else name


def case_name(enum, label):
    if label[0].isdigit():
        ident = last_word(enum).lower() + label
    else:
        ident = lower_leading_word(label)
    return f"`{ident}`" if ident in KEYWORDS else ident


def swift_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def availability(ios, deprecated):
    if deprecated:
        return f"@available(iOS, introduced: {ios}, deprecated: {deprecated})\n"
    return ""


def main():
    check = "--check" in sys.argv
    text = open(SPEC, encoding="utf-8").read()
    secs = sections(text)

    def hap_rows(title, prefix):
        entries = []
        for short, name, ios, notes in secs[title]:
            dep = None
            m = re.search(r"deprecated (\d+\.\d+)", notes)
            if m:
                dep = m.group(1)
            uuid = short.upper().rjust(8, "0") + HAP_BASE_SUFFIX
            entries.append(dict(const=prefix + name, short=name, value=uuid, ios=ios,
                                deprecated=dep, shortID=int(short, 16)))
        return entries

    def string_rows(title, prefix):
        entries = []
        for name, ident, ios in secs[title]:
            entries.append(dict(const=prefix + name, short=name, value=ident.strip("`"), ios=ios,
                                deprecated=None, shortID=None))
        return entries

    services = hap_rows("Service types", "HMServiceType")
    characteristics = hap_rows("Characteristic types", "HMCharacteristicType")
    categories = string_rows("Accessory category types", "HMAccessoryCategoryType")
    formats = string_rows("Metadata formats", "HMCharacteristicMetadataFormat")
    units = string_rows("Metadata units", "HMCharacteristicMetadataUnits")
    properties = string_rows("Characteristic properties", "HMCharacteristicProperty")
    action_sets = string_rows("Action-set types", "HMActionSetType")
    significant = string_rows("Significant events", "HMSignificantEvent")

    keypaths = []
    for name, value in re.findall(r"`(HM\w+KeyPath)` =\s*`([^`]+)`", text):
        keypaths.append(dict(const=name, short=name, value=value, ios="8.0", deprecated=None, shortID=None))
    if len(keypaths) != 3:
        sys.exit(f"expected 3 key paths, found {len(keypaths)}")
    m = re.search(r"`HMErrorDomain` = `([^`]+)`", text)
    if not m or "`HMUserFailedAccessoriesKey` equals its name" not in text.replace("\n", " "):
        sys.exit("HMErrorDomain / HMUserFailedAccessoriesKey sentence not found")
    others = [dict(const="HMErrorDomain", short="HMErrorDomain", value=m.group(1), ios="8.0",
                   deprecated=None, shortID=None),
              dict(const="HMUserFailedAccessoriesKey", short="HMUserFailedAccessoriesKey",
                   value="HMUserFailedAccessoriesKey", ios="8.0", deprecated="27.0", shortID=None)]

    enums = enum_table(text)

    groups = [
        ("Service types", "serviceTypes", services),
        ("Characteristic types", "characteristicTypes", characteristics),
        ("Accessory category types", "accessoryCategoryTypes", categories),
        ("Metadata formats", "metadataFormats", formats),
        ("Metadata units", "metadataUnits", units),
        ("Characteristic properties", "characteristicProperties", properties),
        ("Action-set types", "actionSetTypes", action_sets),
        ("Significant events", "significantEvents", significant),
        ("Predicate key paths", "keyPaths", keypaths),
        ("Error domain and userInfo key", "otherConstants", others),
    ]
    values = [e["value"] for _, _, g in groups for e in g]
    if len(values) != len(set(values)):
        sys.exit("duplicate constant values")

    # Constants.swift: one global per constant (HMSignificantEvent is a string enumeration type).
    c = [HEADER, "\n"]
    for title, _, entries in groups:
        if entries is significant:
            continue
        c.append(f"// MARK: {title}\n\n")
        for e in entries:
            doc = f"/// HAP short ID `{e['shortID']:X}`; iOS {e['ios']}.\n" if e["shortID"] is not None else f"/// iOS {e['ios']}.\n"
            c.append(doc)
            c.append(availability(e["ios"], e["deprecated"]))
            c.append(f"public let {e['const']}: String = {swift_str(e['value'])}\n")
        c.append("\n")
    c.append("// MARK: Significant events\n\n")
    c.append("/// A significant time of day (a string enumeration, as in the Swift API).\n")
    c.append("public struct HMSignificantEvent: RawRepresentable, Hashable, Codable, Sendable {\n")
    c.append("    public let rawValue: String\n")
    c.append("    public init(rawValue: String) { self.rawValue = rawValue }\n")
    c.append("    public init(_ rawValue: String) { self.rawValue = rawValue }\n")
    for e in significant:
        c.append(f"    /// iOS {e['ios']}.\n")
        c.append(f"    public static let {lower_leading_word(e['short'])} = HMSignificantEvent(rawValue: {swift_str(e['value'])})\n")
    c.append("}\n")
    constants = "".join(c)

    # Catalog.swift: tables for lookups and the conformance tests.
    k = [HEADER, "\n", "extension YcodeHomeCatalog {\n"]
    for title, prop, entries in groups:
        k.append(f"    /// {title} ({len(entries)}).\n")
        k.append(f"    public static let {prop}: [YcodeHomeCatalogEntry] = [\n")
        for e in entries:
            sid = f"0x{e['shortID']:X}" if e["shortID"] is not None else "nil"
            dep = swift_str(e["deprecated"]) if e["deprecated"] else "nil"
            k.append(f"        .init(constantName: {swift_str(e['const'])}, name: {swift_str(e['short'])}, "
                     f"identifier: {swift_str(e['value'])}, shortID: {sid}, introduced: {swift_str(e['ios'])}, "
                     f"deprecated: {dep}),\n")
        k.append("    ]\n\n")
    k.append(f"    /// Characteristic value enumerations ({len(enums)}).\n")
    k.append("    public static let valueEnumerations: [YcodeValueEnumerationEntry] = [\n")
    for name, ios, cases in enums:
        cs = ", ".join(f"({v}, {swift_str(label)})" for v, label in cases)
        k.append(f"        .init(name: {swift_str('HMCharacteristicValue' + name)}, introduced: {swift_str(ios)}, cases: [{cs}]),\n")
    k.append("    ]\n}\n")
    catalog = "".join(k)

    # ValueEnums.swift
    v = [HEADER, "\n"]
    for name, ios, cases in enums:
        v.append(f"/// Values of the matching characteristic (HAP wire values); iOS {ios}.\n")
        v.append(f"public enum HMCharacteristicValue{name}: Int, Sendable, CaseIterable, Codable {{\n")
        for num, label in cases:
            v.append(f"    case {case_name(name, label)} = {num}\n")
        v.append("}\n\n")
    value_enums = "".join(v).rstrip("\n") + "\n"

    outputs = {"Constants.swift": constants, "Catalog.swift": catalog, "ValueEnums.swift": value_enums}
    stale = []
    for fname, content in outputs.items():
        path = os.path.join(OUT, fname)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != content:
            stale.append(fname)
            if not check:
                os.makedirs(OUT, exist_ok=True)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
    total = sum(len(g) for _, _, g in groups)
    print(f"{len(services)} services, {len(characteristics)} characteristics, {len(categories)} categories, "
          f"{total} constants, {len(enums)} value enumerations")
    if check and stale:
        sys.exit("stale: " + ", ".join(stale))
    if not check:
        print("wrote " + (", ".join(stale) if stale else "nothing (up to date)"))


if __name__ == "__main__":
    main()
