#!/usr/bin/env python3
"""Embeds the compositor's SPIR-V in Sources/COVVulkan/ov_shaders.h.

Compile the GLSL first (any machine with shaderc, e.g. the Linux hosts):
    glslc -O -o Shaders/layer.vert.spv Shaders/layer.vert
    glslc -O -o Shaders/layer.frag.spv Shaders/layer.frag
then run `python3 -I Scripts/gen_shaders.py` from the package directory.
The .spv files are build intermediates and are not committed.
"""
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
OUT = os.path.join(PKG, "Sources", "COVVulkan", "ov_shaders.h")


def words(path):
    data = open(path, "rb").read()
    assert len(data) % 4 == 0 and struct.unpack_from("<I", data)[0] == 0x07230203, path
    return struct.unpack("<%dI" % (len(data) // 4), data)


def array(name, ws):
    lines = []
    for i in range(0, len(ws), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in ws[i:i + 8]) + ",")
    return "static const uint32_t %s[%d] = {\n%s\n};\n" % (name, len(ws), "\n".join(lines))


out = ["/* Generated by Scripts/gen_shaders.py from Shaders/layer.vert and layer.frag. Do not edit. */",
       "#ifndef OV_SHADERS_H", "#define OV_SHADERS_H", "#include <stdint.h>", ""]
for stage in ("vert", "frag"):
    out.append(array("ov_layer_%s_spv" % stage, words(os.path.join(PKG, "Shaders", "layer.%s.spv" % stage))))
out.append("#endif")
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote", OUT)
