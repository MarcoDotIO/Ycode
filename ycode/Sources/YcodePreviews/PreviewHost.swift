import Foundation
import YcodeSubprocess

/// The preview **host**: a small app, the same for every project, that
/// stays running on the preview device. It polls `plan.json` in its
/// preview directory, loads each new payload with `dlopen`, asks it for
/// one view controller per region and lays them out (scaled) on its
/// screen; it reports on standard output (`YCODE-PREVIEW ready <generation>
/// <ms>`, `YCODE-PREVIEW error <generation> <message>`). See
/// `specs/ide/previews.md` §The preview host.
public enum PreviewHost {
    public static let bundleIdentifier = "dev.ycode.previewhost"
    public static let executableName = "YcodePreviewHost"
    public static let appName = "YcodePreviewHost.app"
    /// The directory the host polls, as the guest sees it (`/tmp` of the
    /// device: `DEV/data/tmp` on the host, `app-install-launch.md` §3.4).
    public static let guestDirectory = "/tmp/ycode-previews"
    /// The same directory under the device directory.
    public static let deviceRelativeDirectory = "data/tmp/ycode-previews"
    /// The source's version: a host built from another version is rebuilt.
    public static let sourceVersion = 4

    /// A line of the host's output, parsed.
    public enum Report: Equatable, Sendable {
        case started
        case ready(generation: Int, milliseconds: Int)
        case error(generation: Int, message: String)
    }

    public static func parseReport(_ line: String) -> Report? {
        guard let r = line.range(of: "YCODE-PREVIEW ") else { return nil }
        let words = line[r.upperBound...].split(separator: " ", maxSplits: 2).map(String.init)
        switch words.first {
        case "started": return .started
        case "ready":
            guard words.count >= 2, let g = Int(words[1]) else { return nil }
            return .ready(generation: g, milliseconds: words.count > 2 ? Int(words[2].split(separator: " ").first ?? "") ?? 0 : 0)
        case "error":
            guard words.count >= 2, let g = Int(words[1]) else { return nil }
            return .error(generation: g, message: words.count > 2 ? words[2] : "")
        default: return nil
        }
    }

    /// The UIKit host's source (iOS, iPadOS, visionOS).
    public static let uikitSource = #"""
    // Ycode preview host (generated by Ycode; specs/ide/previews.md §The preview host).
    import UIKit
    import Darwin

    let previewDirectory = ProcessInfo.processInfo.environment["YCODE_PREVIEW_DIR"] ?? "/tmp/ycode-previews"

    func report(_ s: String) {
        let line = "YCODE-PREVIEW " + s + "\n"
        FileHandle.standardOutput.write(line.data(using: .utf8)!)
        // Also into the preview directory, for an IDE that does not see standard output.
        let path = previewDirectory + "/host.log"
        if let h = FileHandle(forWritingAtPath: path) { h.seekToEndOfFile(); h.write(line.data(using: .utf8)!); h.closeFile() }
        else { FileManager.default.createFile(atPath: path, contents: line.data(using: .utf8)) }
    }

    struct Region: Decodable {
        var preview: Int
        var x: Double, y: Double, width: Double, height: Double
        var scale: Double
        var style: String?
        var dynamicType: String?
        var orientation: String?
        var fits: Bool?
    }

    struct Plan: Decodable {
        var generation: Int
        var payload: String
        var regions: [Region]
    }

    typealias Make = @convention(c) (Int32) -> UnsafeMutableRawPointer?

    let sizes: [String: UIContentSizeCategory] = [
        "xSmall": .extraSmall, "small": .small, "medium": .medium, "large": .large, "xLarge": .extraLarge,
        "xxLarge": .extraExtraLarge, "xxxLarge": .extraExtraExtraLarge, "accessibility1": .accessibilityMedium,
        "accessibility2": .accessibilityLarge, "accessibility3": .accessibilityExtraLarge,
        "accessibility4": .accessibilityExtraExtraLarge, "accessibility5": .accessibilityExtraExtraExtraLarge,
    ]

    final class RootController: UIViewController {
        var loaded: [String: Make] = [:]
        var stamp = ""
        var timer: Timer?
        var tiles: [UIView] = []

        override func viewDidLoad() {
            super.viewDidLoad()
            view.backgroundColor = UIColor(white: 0.93, alpha: 1)
            report("started")
            timer = Timer.scheduledTimer(withTimeInterval: 0.025, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
        }

        override func viewDidAppear(_ animated: Bool) {
            super.viewDidAppear(animated)
            poll()
        }

        func poll() {
            let path = previewDirectory + "/plan.json"
            var st = stat()
            guard stat(path, &st) == 0 else { return }
            let s = "\(st.st_mtimespec.tv_sec).\(st.st_mtimespec.tv_nsec).\(st.st_size).\(st.st_ino)"
            guard s != stamp else { return }
            stamp = s
            guard let data = FileManager.default.contents(atPath: path) else { return }
            guard let plan = try? JSONDecoder().decode(Plan.self, from: data) else { report("error 0 the plan could not be read"); return }
            apply(plan)
        }

        func load(_ payload: String, generation: Int) -> Make? {
            if let f = loaded[payload] { return f }
            guard let h = dlopen(payload, RTLD_NOW | RTLD_LOCAL) else {
                report("error \(generation) " + String(cString: dlerror()).replacingOccurrences(of: "\n", with: " "))
                return nil
            }
            guard let sym = dlsym(h, "ycode_preview_make") else { report("error \(generation) the payload has no ycode_preview_make"); return nil }
            let f = unsafeBitCast(sym, to: Make.self)
            loaded[payload] = f
            return f
        }

        func apply(_ plan: Plan) {
            let t0 = CFAbsoluteTimeGetCurrent()
            guard let make = load(plan.payload, generation: plan.generation) else { return }
            for c in children { c.willMove(toParent: nil); c.view.removeFromSuperview(); c.removeFromParent() }
            tiles.forEach { $0.removeFromSuperview() }
            tiles = []
            for r in plan.regions {
                guard let raw = make(Int32(r.preview)) else { report("error \(plan.generation) no preview \(r.preview)"); continue }
                let vc = Unmanaged<UIViewController>.fromOpaque(raw).takeRetainedValue()
                let tile = UIView(frame: CGRect(x: r.x, y: r.y, width: r.width, height: r.height))
                tile.clipsToBounds = true
                tile.backgroundColor = r.style == "dark" ? .black : .white
                view.addSubview(tile)
                tiles.append(tile)
                addChild(vc)
                if let s = r.style { vc.overrideUserInterfaceStyle = s == "dark" ? .dark : .light }
                if let d = r.dynamicType, let c = sizes[d] { vc.traitOverrides.preferredContentSizeCategory = c }
                if let o = r.orientation, o.hasPrefix("landscape") { vc.traitOverrides.verticalSizeClass = .compact }
                let w = r.width / r.scale, h = r.height / r.scale
                var size = CGSize(width: w, height: h)
                if r.fits == true {
                    let fit = vc.view.systemLayoutSizeFitting(CGSize(width: w, height: UIView.layoutFittingCompressedSize.height),
                                                              withHorizontalFittingPriority: .fittingSizeLevel, verticalFittingPriority: .fittingSizeLevel)
                    if fit.width > 0, fit.height > 0 { size = CGSize(width: min(fit.width, w), height: min(fit.height, h)) }
                }
                vc.view.bounds = CGRect(origin: .zero, size: size)
                vc.view.center = CGPoint(x: r.width / 2, y: r.height / 2)
                vc.view.transform = CGAffineTransform(scaleX: r.scale, y: r.scale)
                tile.addSubview(vc.view)
                vc.didMove(toParent: self)
            }
            view.layoutIfNeeded()
            CATransaction.flush()
            report("ready \(plan.generation) \(Int((CFAbsoluteTimeGetCurrent() - t0) * 1000))")
        }

        override var prefersStatusBarHidden: Bool { false }
    }

    final class SceneDelegate: UIResponder, UIWindowSceneDelegate {
        var window: UIWindow?
        func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options: UIScene.ConnectionOptions) {
            guard let ws = scene as? UIWindowScene else { return }
            let w = UIWindow(windowScene: ws)
            w.rootViewController = RootController()
            w.makeKeyAndVisible()
            window = w
        }
    }

    final class AppDelegate: UIResponder, UIApplicationDelegate {
        func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
            setvbuf(stdout, nil, _IOLBF, 0)
            try? FileManager.default.createDirectory(atPath: previewDirectory, withIntermediateDirectories: true)
            return true
        }
    }

    UIApplicationMain(CommandLine.argc, CommandLine.unsafeArgv, nil, NSStringFromClass(AppDelegate.self))
    """#

