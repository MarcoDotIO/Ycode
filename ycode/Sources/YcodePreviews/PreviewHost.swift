    }

    /// The host's icon (Ycode's own mark: a canvas frame on a teal-to-blue
    /// field), an RGB PNG with stored (uncompressed) deflate blocks, so no
    /// compression library is needed.
    public static func iconPNG(size n: Int) -> Data {
        var raw = [UInt8]()
        raw.reserveCapacity(n * (1 + 3 * n))
        let d = Double(n)
        for y in 0..<n {
            raw.append(0)
            for x in 0..<n {
                let t = Double(x + y) / (2 * d), fx = Double(x), fy = Double(y)
                let outer = fx > d * 0.28 && fx < d * 0.72 && fy > d * 0.22 && fy < d * 0.78
                let inner = fx > d * 0.33 && fx < d * 0.67 && fy > d * 0.28 && fy < d * 0.72
                if outer && !inner { raw += [255, 255, 255] } else { raw += [UInt8(30 + 20 * t), UInt8(160 - 60 * t), UInt8(200 + 40 * t)] }
            }
        }
        func be32(_ v: UInt32) -> [UInt8] { [UInt8(v >> 24), UInt8(v >> 16 & 0xff), UInt8(v >> 8 & 0xff), UInt8(v & 0xff)] }
        func crc32(_ bytes: [UInt8]) -> UInt32 {
            var c: UInt32 = 0xffff_ffff
            for b in bytes {
                c ^= UInt32(b)
                for _ in 0..<8 { c = c & 1 != 0 ? 0xedb8_8320 ^ (c >> 1) : c >> 1 }
            }
            return ~c
        }
        func chunk(_ type: String, _ body: [UInt8]) -> [UInt8] {
            let t = Array(type.utf8)
            return be32(UInt32(body.count)) + t + body + be32(crc32(t + body))
        }
        var z: [UInt8] = [0x78, 0x01]
        var i = 0
        while i < raw.count {
            let len = min(65535, raw.count - i)
            z.append(i + len == raw.count ? 1 : 0)
            z += [UInt8(len & 0xff), UInt8(len >> 8), UInt8(~len & 0xff), UInt8((~len >> 8) & 0xff)]
            z += raw[i..<i + len]
            i += len
        }
        var a: UInt32 = 1, b: UInt32 = 0
        for v in raw { a = (a + UInt32(v)) % 65521; b = (b + a) % 65521 }
        z += be32(b << 16 | a)
        let ihdr = be32(UInt32(n)) + be32(UInt32(n)) + [8, 2, 0, 0, 0]
        return Data([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] + chunk("IHDR", ihdr) + chunk("IDAT", z) + chunk("IEND", []))
    }

    /// The host app's arguments to `xcrun` (one file, unoptimized: it is
    /// built once per platform, deployment target and source version).
    public static func hostArguments(platform: PreviewPlatform, deploymentTarget: String, source: URL, output: URL, moduleCache: URL) -> [String] {
        ["--sdk", platform.sdk, "swiftc", "-target", platform.targetTriple(deploymentTarget: deploymentTarget),
         "-module-name", executableName, "-Onone", "-gnone", "-module-cache-path", moduleCache.standardizedFileURL.path,
         "-o", output.path, source.path]
    }

    /// Builds (or reuses) the host app for a platform and deployment target
    /// under `workDirectory/hosts/<platform>-<target>-v<version>/`.
    public static func build(platform: PreviewPlatform, deploymentTarget: String, workDirectory: URL, xcrun: String = "/usr/bin/xcrun") throws(PreviewFailure) -> URL {
        precondition(platform.usesUIKit, "the Mac host is PreviewMacHost")
        let dir = workDirectory.appendingPathComponent("hosts/\(platform.rawValue)-\(deploymentTarget)-v\(sourceVersion)")
        let app = dir.appendingPathComponent(appName)
        let exe = app.appendingPathComponent(executableName)
        if FileManager.default.isExecutableFile(atPath: exe.path) { return app }
        do {
            try FileManager.default.createDirectory(at: app, withIntermediateDirectories: true)
            try uikitSource.write(to: dir.appendingPathComponent("main.swift"), atomically: true, encoding: .utf8)
            try infoPlist(platform: platform, deploymentTarget: deploymentTarget).write(to: app.appendingPathComponent("Info.plist"), atomically: true, encoding: .utf8)
            // An icon of its own: a new app without one left the home
            // screen frozen in our simulator runs (previews.md §Open questions).
            try iconPNG(size: 120).write(to: app.appendingPathComponent("AppIcon60x60@2x.png"))
            try iconPNG(size: 180).write(to: app.appendingPathComponent("AppIcon60x60@3x.png"))
        } catch { throw .host("could not write the preview host: \(error)") }
        let tmp = dir.appendingPathComponent("\(executableName).tmp")
        let args = hostArguments(platform: platform, deploymentTarget: deploymentTarget, source: dir.appendingPathComponent("main.swift"),
                                 output: tmp, moduleCache: workDirectory.appendingPathComponent("ModuleCache"))
        let out: Subprocess.Output
        do { out = try Subprocess.run(xcrun, args) } catch { throw .host("could not run xcrun: \(error)") }
        guard out.status == 0 else { throw .compile(PreviewCompiler.issues(from: out.stdoutText + out.stderrText, lineMaps: [:])) }
        do { try FileManager.default.moveItem(at: tmp, to: exe) } catch { throw .host("\(error)") }
        // Ad hoc signature for the bundle (the linker signed the executable).
        _ = try? Subprocess.run("/usr/bin/codesign", ["-s", "-", "-f", app.path])
        return app
    }
}
