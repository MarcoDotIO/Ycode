import Foundation
#if canImport(CoreGraphics)
import CoreGraphics
#endif

/// A small Swift package that renders one `#Preview` to a PNG through
/// OpenViews, the open SwiftUI port (`frameworks/swiftui`, round R5), with
/// no window and no GPU: `ycode preview --render` on Linux (and on macOS,
/// where the file's `import SwiftUI` is pointed at the port's renamed
/// modules). See specs/ide/previews.md.
///
/// The package holds the previewed file with every `#Preview` blanked out
/// (lines kept, so diagnostics keep their line numbers) and `@main`
/// removed, plus a `main.swift` that evaluates the chosen preview's body as
/// a view builder and writes `ImageRenderer.pngData` to the path given as
/// its first argument.
public enum PreviewRenderHost {
    /// The size a preview is rendered at when it has no layout trait: a
    /// phone-sized canvas (Ycode's choice for headless rendering).
    public static let defaultCanvas = CGSize(width: 393, height: 852)

    /// Files of the package (relative path → contents).
    public static func files(source text: String, preview: PreviewDeclaration, all previews: [PreviewDeclaration],
                             openViewsPath: String, scale: Double = 2, appleHost: Bool) -> [String: String] {
        guard case .macro(let body) = preview.kind else { return [:] }
        // Blank every #Preview, keeping newlines.
        var units = Array(text.utf16)
        for p in previews {
            guard let r = p.range, r.location >= 0, r.location + r.length <= units.count else { continue }
            for k in r.location..<(r.location + r.length) where units[k] != 10 { units[k] = 32 }
        }
        var file = String(decoding: units, as: UTF16.self)
        file = file.replacingOccurrences(of: "@main", with: "     ")
        let ui = appleHost ? "OpenViews" : "SwiftUI"
        if appleHost {
            file = rewriteImports(file)
        }
        let layout: String
        if let s = preview.fixedSize {
            layout = "content.frame(width: \(Double(s.width)), height: \(Double(s.height)))"
        } else if preview.traits.contains("sizeThatFitsLayout") {
            layout = "content"
        } else {
            layout = "content.frame(width: \(Double(defaultCanvas.width)), height: \(Double(defaultCanvas.height)))"
        }
        let main = """
        // Generated by ycode preview --render: renders "\(preview.name.replacingOccurrences(of: "\"", with: "'"))".
        import Foundation
        import \(ui)

        @MainActor @ViewBuilder
        func ycodePreviewContent() -> some View {
        \(body)
        }

        @MainActor
        func ycodeRenderPreview() -> Int32 {
            let content = ycodePreviewContent()
            let renderer = ImageRenderer(content: \(layout))
            renderer.scale = \(scale)
            renderer.isOpaque = true
            guard CommandLine.arguments.count > 1, let data = renderer.pngData else { return 1 }
            do {
                try data.write(to: URL(fileURLWithPath: CommandLine.arguments[1]))
            } catch {
                return 2
            }
            return 0
        }

        exit(MainActor.assumeIsolated { ycodeRenderPreview() })

        """
        let manifest = """
        // swift-tools-version: 6.0
        // Generated by ycode preview --render.
        import PackageDescription

        let package = Package(
            name: "ycode-preview-host",
            platforms: [.macOS(.v15)],
            dependencies: [.package(path: \(swiftLiteral(openViewsPath)))],
            targets: [
                .executableTarget(name: "PreviewHost",
                                  dependencies: [.product(name: "\(ui)", package: "swiftui")],
                                  path: "Sources/PreviewHost"),
            ]
        )

        """
        return ["Package.swift": manifest, "Sources/PreviewHost/Preview.swift": file, "Sources/PreviewHost/main.swift": main]
    }

    /// `import SwiftUI` → `import OpenViews` (and SwiftUICore → OpenViewsCore)
    /// for Apple hosts, where the port's modules are renamed.
    static func rewriteImports(_ text: String) -> String {
        text.split(separator: "\n", omittingEmptySubsequences: false).map { line -> String in
            let t = line.trimmingCharacters(in: .whitespaces)
            if t == "import SwiftUI" { return line.replacingOccurrences(of: "SwiftUI", with: "OpenViews") }
            if t == "import SwiftUICore" { return line.replacingOccurrences(of: "SwiftUICore", with: "OpenViewsCore") }
            return String(line)
        }.joined(separator: "\n")
    }

    private static func swiftLiteral(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    /// The OpenViews package: `$YCODE_OPENVIEWS`, else `frameworks/swiftui`
    /// found by walking up from each of `starts`.
    public static func locateOpenViews(environment: [String: String], starts: [URL]) -> URL? {
        let fm = FileManager.default
        if let p = environment["YCODE_OPENVIEWS"], fm.fileExists(atPath: p + "/Package.swift") { return URL(fileURLWithPath: p) }
        for start in starts {
            var dir = start.standardizedFileURL
            for _ in 0..<12 {
                let candidate = dir.appendingPathComponent("frameworks/swiftui")
                if fm.fileExists(atPath: candidate.appendingPathComponent("Package.swift").path) { return candidate }
                let parent = dir.deletingLastPathComponent()
                if parent.path == dir.path { break }
                dir = parent
            }
        }
        return nil
    }
}
