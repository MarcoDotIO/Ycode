// SwiftUI previews in the Linux IDE's canvas (specs/ide/previews.md §Linux,
// "The Linux canvas"): the payload path of the Mac and the simulator, with
// OpenViews (frameworks/swiftui) as the toolkit. A long-lived host process,
// built once against OpenViews in release, exports OpenViews' symbols
// (`--export-dynamic`); each edit compiles the module and the focused file's
// previews into a small shared library (a payload) against the host's
// modules, and the host `dlopen`s it and calls the payload's
// `ycode_preview_render`, which renders one preview with `ImageRenderer` to a
// PNG. No SwiftPM build per edit, no new process.

extension PreviewPayloadGenerator {
    /// The C entry point of an OpenViews payload: renders preview `index`
    /// to a PNG file (`ycode_preview_render(index, dark, width, height,
    /// scale, path)`; 0 × 0 is the view's ideal size).
    public static let renderSymbol = "ycode_preview_render"

    /// The support file of an OpenViews payload: `__ycodeHost` turns a
    /// preview body into an `AnyView`; `ycode_preview_render(index, dark,
    /// dynamicType, width, height, scale, path)` renders one (dynamic type:
    /// an index into `DynamicTypeSize.allCases`, or -1; status 0: written,
    /// 1: no such preview, 2: nothing to draw, 3: the file could not be
    /// written).
    public static func openViewsSupportFile(count: Int) -> String {
        var out = """
        // Generated by Ycode for previews. Do not edit.
        import Foundation
        import SwiftUI

        @MainActor func __ycodeHost(@ViewBuilder _ make: @MainActor () -> any View) -> AnyView { AnyView(make()) }

        @MainActor func __ycodePreviewView(_ index: Int) -> AnyView? {
            switch index {

        """
        for i in 0..<count { out += "    case \(i): return __ycodePreview_\(i)()\n" }
        out += """
            default: return nil
            }
        }

        @_cdecl("\(countSymbol)") public func __ycodePreviewCount() -> Int32 { \(count) }

        @_cdecl("\(renderSymbol)") public func __ycodePreviewRender(_ index: Int32, _ dark: Int32, _ dynamicType: Int32, _ width: Double,
                                                               _ height: Double, _ scale: Double, _ path: UnsafePointer<CChar>) -> Int32 {
            let out = String(cString: path)
            return MainActor.assumeIsolated {
                guard let view = __ycodePreviewView(Int(index)) else { return 1 }
                var content = AnyView(view.environment(\\.colorScheme, dark != 0 ? .dark : .light))
                if dynamicType >= 0, Int(dynamicType) < DynamicTypeSize.allCases.count {
                    content = AnyView(content.dynamicTypeSize(DynamicTypeSize.allCases[Int(dynamicType)]))
                }
                let sized = width > 0 && height > 0 ? AnyView(content.frame(width: width, height: height)) : content
                let renderer = ImageRenderer(content: sized.background(dark != 0 ? Color.black : Color.white))
                renderer.scale = scale
                guard let data = renderer.pngData else { return 2 }
                return (try? data.write(to: URL(fileURLWithPath: out))) != nil ? 0 : 3
            }
        }

        """
        return out
    }
}

/// The Linux IDE's preview host: a SwiftPM package written to the cache
/// folder, built once in release against OpenViews, that reads one JSON
/// request per line (`Request`) and answers `YCODE-PREVIEW
/// ready <generation> <ms>` or `YCODE-PREVIEW error <generation> <message>`.
public enum PreviewOpenViewsHost {
    /// One render request: the payload and the pictures to make.
    public struct Request: Codable, Equatable, Sendable {
        public struct Item: Codable, Equatable, Sendable {
            /// The preview's index in the payload.
            public var index: Int
            /// The size in points, or 0 × 0 for the view's ideal size.
            public var width: Double
            public var height: Double
            public var dark: Bool
            /// A `DynamicTypeSize` case name, or nil.
            public var dynamicType: String?
            /// The PNG to write (absolute).
            public var file: String
            public init(index: Int, width: Double, height: Double, dark: Bool = false, dynamicType: String? = nil, file: String) {
                self.index = index
                self.width = width
                self.height = height
                self.dark = dark
                self.dynamicType = dynamicType
                self.file = file
            }
        }
        public var generation: Int
        public var payload: String
        public var items: [Item]
        public init(generation: Int, payload: String, items: [Item]) {
            self.generation = generation
            self.payload = payload
            self.items = items
        }

        public func line() -> String {
            let e = JSONEncoder()
            e.outputFormatting = [.sortedKeys]
            return String(decoding: (try? e.encode(self)) ?? Data(), as: UTF8.self) + "\n"
        }
    }

    public static let productName = "YcodePreviewOVHost"
    /// A host built from another version is rebuilt (the folder carries it).
    public static let sourceVersion = 1
    /// Pixels per point of the rendered PNGs.
    public static let scale = 2.0

    public static let source = #"""
    // Ycode preview host for OpenViews (generated by Ycode; specs/ide/previews.md §Linux).
    import Foundation
    import SwiftUI
    #if canImport(Glibc)
    import Glibc
    #endif

    struct Item: Decodable { var index: Int; var width: Double; var height: Double; var dark: Bool; var dynamicType: String?; var file: String }
    struct Request: Decodable { var generation: Int; var payload: String; var items: [Item] }
    typealias Render = @convention(c) (Int32, Int32, Int32, Double, Double, Double, UnsafePointer<CChar>) -> Int32
    let dynamicTypes = ["xSmall", "small", "medium", "large", "xLarge", "xxLarge", "xxxLarge",
                        "accessibility1", "accessibility2", "accessibility3", "accessibility4", "accessibility5"]

    func say(_ s: String) { print("YCODE-PREVIEW " + s); fflush(stdout) }

    // The host itself draws nothing; this keeps OpenViews linked in (the
    // payloads use its symbols) without running it.
    @MainActor func linkOpenViews() -> Data? { ImageRenderer(content: Text(verbatim: "").frame(width: 1, height: 1)).pngData }
    if CommandLine.arguments.contains("--self-test") { _ = MainActor.assumeIsolated { linkOpenViews() } }

    // Never outlive the parent (the IDE or a test): end at the end of the
    // input, and when reparented.
    let parent = getppid()
    if parent == 1 { exit(0) }
    Thread.detachNewThread {
        while true {
            sleep(1)
            if getppid() != parent { _exit(0) }
        }
    }

    var loaded: [String: Render] = [:]
    say("started")
    while let line = readLine() {
        guard let r = try? JSONDecoder().decode(Request.self, from: Data(line.utf8)) else { say("error 0 the request could not be read"); continue }
        let t0 = Date()
        var render = loaded[r.payload]
        if render == nil {
            guard let h = dlopen(r.payload, RTLD_NOW | RTLD_LOCAL) else {
                say("error \(r.generation) " + String(cString: dlerror()).replacingOccurrences(of: "\n", with: " "))
                continue
            }
            guard let sym = dlsym(h, "ycode_preview_render") else { say("error \(r.generation) the payload has no ycode_preview_render"); continue }
            render = unsafeBitCast(sym, to: Render.self)
            loaded[r.payload] = render
        }
        var failure: String?
        for item in r.items where failure == nil {
            let type = Int32(item.dynamicType.flatMap { dynamicTypes.firstIndex(of: $0) } ?? -1)
            let status = item.file.withCString { render!(Int32(item.index), item.dark ? 1 : 0, type, item.width, item.height, 2, $0) }
            if status == 1 { failure = "no preview \(item.index)" }
            else if status == 2 { failure = "preview \(item.index) has nothing to draw" }
            else if status != 0 { failure = "could not write preview \(item.index)" }
        }
        if let failure { say("error \(r.generation) \(failure)") } else { say("ready \(r.generation) \(Int(Date().timeIntervalSince(t0) * 1000))") }
    }
    """#

    /// The host package's manifest: the host executable on the OpenViews
    /// package at `openViewsPath`, its symbols exported so payloads link
    /// against it at load time.
    public static func manifest(openViewsPath: String) -> String {
        let path = "\"" + openViewsPath.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
        return """
        // swift-tools-version: 6.0
        // Generated by Ycode for previews (specs/ide/previews.md §Linux). Do not edit.
        import PackageDescription

        let package = Package(
            name: "ycode-preview-host",
            platforms: [.macOS(.v15)],
            dependencies: [.package(path: \(path))],
            targets: [
                .executableTarget(name: "\(productName)", dependencies: [.product(name: "SwiftUI", package: "swiftui")],
                                  path: "Sources/\(productName)",
                                  swiftSettings: [.swiftLanguageMode(.v5)],
                                  linkerSettings: [.unsafeFlags(["-Xlinker", "--export-dynamic"])]),
            ]
        )

        """
    }

    /// Where the host package lives: one folder per OpenViews checkout and
    /// source version under `<cache>/ycode/preview-host`.
    public static func packageDirectory(cacheRoot: URL, openViews: URL) -> URL {
        let tag = String(UInt64(bitPattern: Int64(PreviewInputs.hash(openViews.standardizedFileURL.path))), radix: 16)
        return cacheRoot.appendingPathComponent("ycode/preview-host/v\(sourceVersion)-\(tag)")
    }

    /// A built host and what a payload needs to compile against it.
    public struct Built: Equatable, Sendable {
        public var executable: URL
        /// `-I` and `-Xcc` flags that find OpenViews' Swift and C modules.
        public var moduleFlags: [String]
        public init(executable: URL, moduleFlags: [String]) {
            self.executable = executable
            self.moduleFlags = moduleFlags
        }
    }

    /// The flags that make OpenViews' modules visible to a payload: the
    /// build's products folder (Swift modules), every module map SwiftPM
    /// generated, and the C targets' public headers of the port.
    public static func moduleFlags(binPath: URL, packageDirectory: URL, openViews: URL) -> [String] {
        let fm = FileManager.default
        var flags = ["-I", binPath.path]
        var maps: [String] = []
        let build = packageDirectory.appendingPathComponent(".build").resolvingSymlinksInPath()
        let bin = binPath.resolvingSymlinksInPath().path
        if let e = fm.enumerator(at: build, includingPropertiesForKeys: nil) {
            for case let url as URL in e {
                // SwiftPM's own build system: <bin>/<Target>.build/module.modulemap;
                // swift-build: Intermediates.noindex/GeneratedModuleMaps-<platform>/<Target>.modulemap.
                let u = url.resolvingSymlinksInPath()
                let p = u.path
                if p.hasSuffix(".modulemap"), p.contains("/GeneratedModuleMaps") || u.deletingLastPathComponent().deletingLastPathComponent().path == bin {
                    maps.append(p)
                }
            }
        }
        for m in Set(maps).sorted() { flags += ["-Xcc", "-fmodule-map-file=" + m] }
        let sources = openViews.appendingPathComponent("Sources")
        for t in ((try? fm.contentsOfDirectory(atPath: sources.path)) ?? []).sorted() {
            let inc = sources.appendingPathComponent(t).appendingPathComponent("include")
            if fm.fileExists(atPath: inc.appendingPathComponent("module.modulemap").path) { flags += ["-Xcc", "-I" + inc.path] }
        }
        return flags
    }

    /// The payload's `swiftc` arguments: one whole-module, unoptimized job
    /// into a shared library whose OpenViews symbols resolve against the
    /// host when it is loaded.
    public static func payloadArguments(sources: [URL], output: URL, moduleName: String, moduleFlags: [String]) -> [String] {
        var args = ["-emit-library", "-module-name", moduleName, "-parse-as-library", "-wmo", "-Onone", "-gnone",
                    "-D", "DEBUG", "-D", "YCODE_PREVIEW", "-swift-version", "5"]
        #if os(macOS)
        args += ["-Xlinker", "-undefined", "-Xlinker", "dynamic_lookup"]
        #endif
        return args + moduleFlags + ["-o", output.path] + sources.map(\.path)
    }

    nonisolated(unsafe) private static var builtCache: [String: Built] = [:]
    private static let lock = NSLock()

    /// Writes and builds the host (once per OpenViews checkout; later calls
    /// return the cached result). Blocks for minutes the first time.
    public static func build(openViews: URL, cacheRoot: URL, progress: (String) -> Void = { _ in }) throws(PreviewFailure) -> Built {
        let dir = packageDirectory(cacheRoot: cacheRoot, openViews: openViews)
        lock.lock()
        if let b = builtCache[dir.path] { lock.unlock(); return b }
        lock.unlock()
        let files = ["Package.swift": manifest(openViewsPath: openViews.standardizedFileURL.path),
                     "Sources/\(productName)/main.swift": source]
        do {
            for (path, text) in files { try PreviewPayloadGenerator.write(text, to: dir.appendingPathComponent(path)) }
        } catch { throw .host("could not write the preview host in \(dir.path): \(error)") }
        progress("Building the preview host")
        let swift = ["swift", "build", "--package-path", dir.path, "-c", "release", "--product", productName]
        let built = PreviewChild.run(swift, timeout: 3600)
        guard built.status == 0 else {
            throw .host("The preview host did not build: " + (built.output.split(separator: "\n").last { $0.contains("error") }.map(String.init) ?? "status \(built.status)"))
        }
        let shown = PreviewChild.run(["swift", "build", "--package-path", dir.path, "-c", "release", "--show-bin-path"], timeout: 600)
        let bin = URL(fileURLWithPath: shown.output.split(separator: "\n").last.map { String($0).trimmingCharacters(in: .whitespaces) } ?? "")
        let exe = bin.appendingPathComponent(productName)
        guard FileManager.default.isExecutableFile(atPath: exe.path) else { throw .host("The preview host was not found in \(bin.path)") }
        let b = Built(executable: exe, moduleFlags: moduleFlags(binPath: bin, packageDirectory: dir, openViews: openViews))
        lock.lock()
        builtCache[dir.path] = b
        lock.unlock()
        return b
    }

    /// Compiles a payload with the toolchain's `swiftc`; errors map back
    /// to the user's files and lines.
    public static func compilePayload(_ sources: PreviewPayloadGenerator.Sources, output: URL, moduleName: String,
                                      built: Built) throws(PreviewFailure) {
        try? FileManager.default.removeItem(at: output)
        let r = PreviewChild.run(["swiftc"] + payloadArguments(sources: sources.files, output: output, moduleName: moduleName,
                                                               moduleFlags: built.moduleFlags), timeout: 600)
        guard r.status == 0, FileManager.default.fileExists(atPath: output.path) else {
            throw .compile(PreviewCompiler.issues(from: r.output, lineMaps: sources.lineMaps))
        }
    }

}

/// Bounded children of the preview path (a build, a compile): output and
/// status, stopped (SIGINT, SIGTERM, SIGKILL) after `timeout` seconds.
public enum PreviewChild {
    public static func run(_ arguments: [String], timeout: TimeInterval) -> (status: Int32, output: String) {
        MainThreadGuard.blockingCall(arguments.prefix(2).joined(separator: " "))
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/env")
        p.arguments = arguments
        p.standardInput = FileHandle.nullDevice
        guard let pipe = try? SpawnPipe(childReads: false) else { return (127, "could not run \(arguments.first ?? "")") }
        p.standardOutput = pipe.childEnd
        p.standardError = pipe.childEnd
        guard (try? p.runWithSignalsUnblocked(closingChildEndsOf: pipe)) != nil else { return (127, "could not run \(arguments.first ?? "")") }
        final class Box: @unchecked Sendable {
            let lock = NSLock()
            var data = Data()
        }
        let box = Box(), done = DispatchSemaphore(value: 0)
        let reader = pipe.fileHandleForReading
        Thread.detachNewThread {
            let d = reader.readDataToEndOfFile()
            box.lock.lock(); box.data = d; box.lock.unlock()
            done.signal()
        }
        func exited(within seconds: TimeInterval) -> Bool {
            let deadline = Date().addingTimeInterval(seconds)
            while p.isRunning && Date() < deadline { usleep(10_000) }
            return !p.isRunning
        }
        var note = ""
        if !exited(within: timeout) {
            // As Control-C: the build or compiler and the jobs it started.
            for sig in [SIGINT, SIGTERM, SIGKILL] where p.isRunning {
                ChildSignals.send(sig, to: p.processIdentifier)
                if exited(within: 2) { break }
            }
            note = "\n\(arguments.first ?? "") did not finish in \(Int(timeout)) s and was stopped"
        }
        _ = done.wait(timeout: .now() + 10)
        box.lock.lock(); defer { box.lock.unlock() }
        return (note.isEmpty ? p.terminationStatus : -1, String(decoding: box.data, as: UTF8.self) + note)
    }
}

/// A running preview host (the Linux IDE's OpenViews host): one JSON
/// request per line in, `YCODE-PREVIEW` reports out; no wait is unbounded
/// (`requestTimeout`), and it ends with its parent.
public final class PreviewHostProcess: @unchecked Sendable {
    private let process = Process()
    private let input: SpawnPipe, output: SpawnPipe
    private let ioLock = NSLock()
    private var buffer = Data()
    private var inputClosed = false
    public private(set) var loads = 0
    /// How long one request may take before the host is considered hung.
    nonisolated(unsafe) public static var requestTimeout: TimeInterval = 120

    public init(executable: URL) throws {
        input = try SpawnPipe(childReads: true)
        output = try SpawnPipe(childReads: false)
        #if os(Linux)
        // A write to a host that ended fails with EPIPE instead of ending the IDE.
        signal(SIGPIPE, SIG_IGN)
        #else
        _ = fcntl(input.fileHandleForWriting.fileDescriptor, F_SETNOSIGPIPE, 1)
        #endif
        process.executableURL = executable
        process.standardInput = input.childEnd
        process.standardOutput = output.childEnd
        process.standardError = FileHandle.nullDevice
        try process.runWithSignalsUnblocked(closingChildEndsOf: input, output)
    }

    public var pid: Int32 { process.processIdentifier }
    public var isRunning: Bool { process.isRunning }

    /// Closes the input, then SIGTERM, then SIGKILL, each after `grace`.
    public func stop(grace: TimeInterval = 2) {
        ioLock.lock()
        if !inputClosed { inputClosed = true; try? input.fileHandleForWriting.close() }
        ioLock.unlock()
        func wait(_ seconds: TimeInterval) -> Bool {
            let deadline = Date().addingTimeInterval(seconds)
            while process.isRunning && Date() < deadline { usleep(20_000) }
            return !process.isRunning
        }
        guard process.isRunning else { return }
        if wait(grace) { return }
        kill(pid, SIGTERM)
        if wait(grace) { return }
        kill(pid, SIGKILL)
        _ = wait(grace)
    }

    private func readLine(deadline: Date) -> String? {
        let fd = output.fileHandleForReading.fileDescriptor
        while true {
            if let nl = buffer.firstIndex(of: 0x0A) {
                let line = String(decoding: buffer[buffer.startIndex..<nl], as: UTF8.self)
                buffer.removeSubrange(buffer.startIndex...nl)
                return line
            }
            let left = deadline.timeIntervalSinceNow
            guard left > 0 else { return nil }
            var p = pollfd(fd: fd, events: Int16(POLLIN), revents: 0)
            let r = poll(&p, 1, Int32(min(left, 1) * 1000))
            if r < 0 && errno != EINTR { return nil }
            if r <= 0 { continue }
            var chunk = [UInt8](repeating: 0, count: 4096)
            let n = read(fd, &chunk, chunk.count)
            if n <= 0 { return nil }
            buffer.append(contentsOf: chunk[0..<n])
        }
    }

    /// Sends a request and waits for its answer (nil: the host ended, or
    /// did not answer in `requestTimeout` and was stopped).
    public func send(_ r: PreviewOpenViewsHost.Request, newPayload: Bool) -> PreviewHost.Report? {
        MainThreadGuard.blockingCall("preview host request")
        ioLock.lock()
        guard !inputClosed, process.isRunning else { ioLock.unlock(); return nil }
        if newPayload { loads += 1 }
        let line = Data(r.line().utf8)
        let ok = line.withUnsafeBytes { b in write(input.fileHandleForWriting.fileDescriptor, b.baseAddress, b.count) == b.count }
        ioLock.unlock()
        guard ok else { stop(); return nil }
        let deadline = Date().addingTimeInterval(Self.requestTimeout)
        while let line = readLine(deadline: deadline) {
            guard let report = PreviewHost.parseReport(line) else { continue }
            switch report {
            case .started: continue
            case .ready(let g, _), .error(let g, _): if g == r.generation || g == 0 { return report }
            }
        }
        stop(grace: 0.5)
        return nil
    }
}
