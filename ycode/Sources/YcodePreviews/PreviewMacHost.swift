import Foundation
import YcodeSubprocess

/// The Mac's preview host: a long-lived process that loads payloads
/// (`PreviewPayloadGenerator` for `.macOS`) and renders their previews
/// offscreen to PNG files, so a macOS preview refresh costs one payload
/// compile instead of a SwiftPM build and a new process. It reads one JSON
/// request per line on standard input and answers `YCODE-PREVIEW ready
/// <generation> <ms>` or `YCODE-PREVIEW error <generation> <message>` on
/// standard output. See `specs/ide/previews.md` §The macOS host.
public enum PreviewMacHost {
    public static let executableName = "YcodePreviewMacHost"
    public static let sourceVersion = 2

    /// One render request.
    public struct Request: Codable, Equatable, Sendable {
        public struct Item: Codable, Equatable, Sendable {
            public var index: Int
            /// A fixed size, or 0 × 0 for the fitting size.
            public var width: Double
            public var height: Double
            public init(index: Int, width: Double = 0, height: Double = 0) {
                self.index = index
                self.width = width
                self.height = height
            }
        }
        public var generation: Int
        public var payload: String
        public var output: String
        public var schemes: [String]
        public var items: [Item]
        public init(generation: Int, payload: String, output: String, schemes: [String], items: [Item]) {
            self.generation = generation
            self.payload = payload
            self.output = output
            self.schemes = schemes
            self.items = items
        }

        public func line() -> String {
            let e = JSONEncoder()
            e.outputFormatting = [.sortedKeys]
            return String(decoding: (try? e.encode(self)) ?? Data(), as: UTF8.self) + "\n"
        }
    }

    public static let source = #"""
    // Ycode preview host for the Mac (generated by Ycode; specs/ide/previews.md §The macOS host).
    import AppKit
    import Darwin

    struct Item: Decodable { var index: Int; var width: Double; var height: Double }
    struct Request: Decodable { var generation: Int; var payload: String; var output: String; var schemes: [String]; var items: [Item] }
    typealias Make = @convention(c) (Int32) -> UnsafeMutableRawPointer?

    func say(_ s: String) { print("YCODE-PREVIEW " + s); fflush(stdout) }

    @MainActor func render(_ vc: NSViewController, size: CGSize?, dark: Bool, to path: String) -> Bool {
        let appearance = NSAppearance(named: dark ? .darkAqua : .aqua)
        let view = vc.view
        view.appearance = appearance
        var s = size ?? view.fittingSize
        if s.width < 1 || s.height < 1 || s.width > 4000 || s.height > 4000 { s = CGSize(width: 320, height: 240) }
        let window = NSWindow(contentRect: CGRect(origin: .zero, size: s), styleMask: [.borderless], backing: .buffered, defer: true)
        window.appearance = appearance
        window.contentViewController = vc
        window.setContentSize(s)
        view.frame = CGRect(origin: .zero, size: s)
        view.layoutSubtreeIfNeeded()
        guard let rep = view.bitmapImageRepForCachingDisplay(in: view.bounds) else { return false }
        view.cacheDisplay(in: view.bounds, to: rep)
        window.contentViewController = nil
        guard let png = rep.representation(using: .png, properties: [:]) else { return false }
        return (try? png.write(to: URL(fileURLWithPath: path))) != nil
    }

    @MainActor func handle(_ r: Request, loaded: inout [String: Make]) {
        let t0 = CFAbsoluteTimeGetCurrent()
        var make = loaded[r.payload]
        if make == nil {
            guard let h = dlopen(r.payload, RTLD_NOW | RTLD_LOCAL) else {
                say("error \(r.generation) " + String(cString: dlerror()).replacingOccurrences(of: "\n", with: " ")); return
            }
            guard let sym = dlsym(h, "ycode_preview_make") else { say("error \(r.generation) the payload has no ycode_preview_make"); return }
            make = unsafeBitCast(sym, to: Make.self)
            loaded[r.payload] = make
        }
        for scheme in r.schemes {
            for item in r.items {
                guard let raw = make!(Int32(item.index)) else { say("error \(r.generation) no preview \(item.index)"); return }
                let vc = Unmanaged<NSViewController>.fromOpaque(raw).takeRetainedValue()
                let size = item.width > 0 && item.height > 0 ? CGSize(width: item.width, height: item.height) : nil
                if !render(vc, size: size, dark: scheme == "dark", to: r.output + "/\(item.index)-\(scheme).png") {
                    say("error \(r.generation) could not render preview \(item.index)"); return
                }
            }
        }
        say("ready \(r.generation) \(Int((CFAbsoluteTimeGetCurrent() - t0) * 1000))")
    }

    // The host never outlives its parent (Ycode or a test process): it ends
    // at the end of its input, at SIGTERM (the default action, whatever AppKit
    // sets up), and when it is reparented because its parent went away
    // (launchd, pid 1, adopts it: a parent that went before this line).
    let parent = getppid()
    if parent == 1 { exit(0) }
    Thread.detachNewThread {
        while true {
            sleep(1)
            if getppid() != parent { _exit(0) }
        }
    }

    MainActor.assumeIsolated {
        let app = NSApplication.shared
        app.setActivationPolicy(.prohibited)
        signal(SIGTERM, SIG_DFL)
        var loaded: [String: Make] = [:]
        say("started")
        while let line = readLine() {
            guard let r = try? JSONDecoder().decode(Request.self, from: Data(line.utf8)) else { say("error 0 the request could not be read"); continue }
            handle(r, loaded: &loaded)
        }
    }
    """#

    /// The deployment target payloads and the host use on this Mac: the
    /// SDK's version, so previewed code may use every API the SDK has.
    public static func deploymentTarget(sdkVersion: String) -> String {
        sdkVersion.split(separator: ".").prefix(2).joined(separator: ".")
    }

    public static func hostArguments(deploymentTarget: String, source: URL, output: URL, moduleCache: URL) -> [String] {
        ["--sdk", "macosx", "swiftc", "-target", PreviewPlatform.macOS.targetTriple(deploymentTarget: deploymentTarget),
         "-module-name", executableName, "-Onone", "-gnone", "-module-cache-path", moduleCache.standardizedFileURL.path,
         "-o", output.path, source.path]
    }

    /// Builds (or reuses) the Mac host under `workDirectory/hosts/macOS-<target>-v<version>/`.
    public static func build(deploymentTarget: String, workDirectory: URL, xcrun: String = "/usr/bin/xcrun") throws(PreviewFailure) -> URL {
        let dir = workDirectory.appendingPathComponent("hosts/macOS-\(deploymentTarget)-v\(sourceVersion)")
        let exe = dir.appendingPathComponent(executableName)
        if FileManager.default.isExecutableFile(atPath: exe.path) { return exe }
        let src = dir.appendingPathComponent("main.swift")
        do {
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            try source.write(to: src, atomically: true, encoding: .utf8)
        } catch { throw .host("could not write the preview host: \(error)") }
        let tmp = dir.appendingPathComponent(executableName + ".tmp")
        let out: Subprocess.Output
        let cache = PreviewModuleCache.prepare(workDirectory.appendingPathComponent("ModuleCache"))
        do {
            out = try PreviewModuleCache.retryingAfterCrash(cache) {
                try Subprocess.run(xcrun, hostArguments(deploymentTarget: deploymentTarget, source: src, output: tmp, moduleCache: cache))
            } crashed: { $0.status != 0 && PreviewModuleCache.looksLikeCompilerCrash($0.stdoutText + "\n" + $0.stderrText) }
        } catch { throw .host("could not run xcrun: \(error)") }
        guard out.status == 0 else { throw .compile(PreviewCompiler.issues(from: out.stdoutText + out.stderrText, lineMaps: [:])) }
        do { try FileManager.default.moveItem(at: tmp, to: exe) } catch { throw .host("\(error)") }
        return exe
    }
}
