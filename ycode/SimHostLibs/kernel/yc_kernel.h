/* The current thread's TSD array, or NULL while no base is set. */
static inline yc_uintptr_t *yc_tsd_base(void)
{
    yc_uintptr_t base;
    __asm__ volatile("mrs %0, tpidrro_el0" : "=r"(base));
    return (yc_uintptr_t *)base;
}

/* ---- _libkernel_functions, version 5 (128 bytes, section 2.1) ---- */
struct yc_libkernel_functions {
    unsigned long version;
    void *(*dlsym)(void *handle, const char *name);
    void *(*malloc)(yc_size_t size);
    void (*free)(void *ptr);
    void *(*realloc)(void *ptr, yc_size_t size);
    void (*pthread_exit_if_canceled)(int error);
    void *reserved[5];
    void (*pthread_clear_qos_tsd)(yc_port_t thread);                       /* v3 */
    int (*pthread_current_stack_contains_np)(const void *addr, yc_size_t len); /* v4 */
    void *(*malloc_type_malloc)(yc_size_t size, yc_u64 type_id);           /* v5 */
    void (*malloc_type_free)(void *ptr, yc_u64 type_id);
    void *(*malloc_type_realloc)(void *ptr, yc_size_t size, yc_u64 type_id);
};
_Static_assert(sizeof(struct yc_libkernel_functions) == 128, "v5 table is 128 bytes");

/* ---- _libkernel_voucher_functions, version 3 (48 bytes, section 2.3) ---- */
struct yc_libkernel_voucher_functions {
    unsigned long version;
    int (*voucher_mach_msg_set)(void *msg);
    void (*voucher_mach_msg_clear)(void *msg);
    void *(*voucher_mach_msg_adopt)(void *msg);
    void (*voucher_mach_msg_revert)(void *state);
    yc_u32 (*voucher_mach_msg_fill_aux)(void *aux, yc_u32 size); /* v3 */
};
_Static_assert(sizeof(struct yc_libkernel_voucher_functions) == 48, "v3 table is 48 bytes");

