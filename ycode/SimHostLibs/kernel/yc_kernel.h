/* ---- Commpage, RW data page (darwin-process-start.md section 3.2) ---- */
#define YC_COMMPAGE_RW 0xFFFFFC000ull
#define YC_COMM_CPU_CAPABILITIES64 0x010
#define YC_COMM_USER_PAGE_SHIFT_64 0x025
#define YC_COMM_KERNEL_PAGE_SHIFT 0x037
