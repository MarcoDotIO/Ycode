import Foundation

// codegen-tool <input.codegen> <output.swift>
// Each `name = text` line of the input becomes `public static let name = "text"`
// in an enum named after the input file.
let args = CommandLine.arguments
guard args.count == 3 else {
    FileHandle.standardError.write(Data("usage: codegen-tool <input.codegen> <output.swift>\n".utf8))
    exit(64)
}
let input = URL(fileURLWithPath: args[1])
let name = input.deletingPathExtension().lastPathComponent
let text = (try? String(contentsOf: input, encoding: .utf8)) ?? ""
var out = "// Generated by codegen-tool from \(input.lastPathComponent). Do not edit.\npublic enum \(name) {\n"
for line in text.split(separator: "\n") {
    let parts = line.split(separator: "=", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespaces) }
    guard parts.count == 2, !parts[0].isEmpty else { continue }
    let value = parts[1].replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
    out += "    public static let \(parts[0]) = \"\(value)\"\n"
}
out += "}\n"
do { try out.write(toFile: args[2], atomically: true, encoding: .utf8) } catch {
    FileHandle.standardError.write(Data("codegen-tool: \(error)\n".utf8))
    exit(1)
}
