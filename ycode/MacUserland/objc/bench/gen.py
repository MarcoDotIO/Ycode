#!/usr/bin/env python3
# gen.py - generates the class-heavy parts of the Objective-C benchmark
# (specs/macos/objc-runtime.md §12) into <out dir>:
#   bench_gen.m   1000 classes R<i> (5 instance + 1 class method each) for
#                 realization; 50 classes U<i> with 200 methods m<j> for
#                 uncached sends; tables of their class objects
#   cats<t>.m     1000 categories (4 methods each) on the R<i>, built as a
#                 bundle; five of them (t = 0-4) for five trials. Each
#                 bundle's control is a copy with the sections renamed so
#                 that no runtime reads them (same mapping and binding work)
#
# Usage: python3 -I gen.py <out dir>
import os
import sys

R, U, UM, CM = 1000, 50, 200, 4
out = sys.argv[1]
os.makedirs(out, exist_ok=True)

g = ["// Generated by gen.py. Do not edit.", "#include <objc/NSObject.h>", ""]
for i in range(R):
    g.append(f"@interface R{i} : NSObject @end")
    g.append(f"@implementation R{i}")
    g.append(f"+ (int)c{i} {{ return {i}; }}")
    for j in range(5):
        g.append(f"- (int)r{j} {{ return {i + j}; }}")
    g.append("@end")
for i in range(U):
    g.append(f"@interface U{i} : NSObject @end")
    g.append(f"@implementation U{i}")
    for j in range(UM):
        g.append(f"- (void)m{j} {{}}")
    g.append("@end")
for i in range(R):
    g.append(f'extern char OBJC_CLASS_$_R{i} __asm("_OBJC_CLASS_$_R{i}");')
for i in range(U):
    g.append(f'extern char OBJC_CLASS_$_U{i} __asm("_OBJC_CLASS_$_U{i}");')
g.append(f"const int gen_r_count = {R}, gen_u_count = {U}, gen_u_methods = {UM};")
g.append("Class gen_r_classes[] = {" + ", ".join(f"(Class)&OBJC_CLASS_$_R{i}" for i in range(R)) + "};")
g.append("Class gen_u_classes[] = {" + ", ".join(f"(Class)&OBJC_CLASS_$_U{i}" for i in range(U)) + "};")
g.append("const char *gen_u_names[] = {" + ", ".join(f'"m{j}"' for j in range(UM)) + "};")
with open(os.path.join(out, "bench_gen.m"), "w") as f:
    f.write("\n".join(g) + "\n")

for t in range(5):
    c = ["// Generated by gen.py. Do not edit.", "#include <objc/NSObject.h>", ""]
    for i in range(R):
        c.append(f"@interface R{i} : NSObject @end")
        c.append(f"@interface R{i} (Cat{t}) @end")
        c.append(f"@implementation R{i} (Cat{t})")
        for j in range(CM):
            c.append(f"- (int)cat{t}_{j} {{ return {i * 10 + j}; }}")
        c.append("@end")
    with open(os.path.join(out, f"cats{t}.m"), "w") as f:
        f.write("\n".join(c) + "\n")
